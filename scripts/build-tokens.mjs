import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import path from 'node:path';
const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
const tokens=JSON.parse(readFileSync(path.join(root,'src/design-system/tokens.json'),'utf8'));
const rem=n=>`${Number((n/16).toFixed(5))}rem`;
let out=['/* AUTO-GENERATED by npm run tokens:build — edit src/design-system/tokens.json */','',':root {'];
for(const [k,v] of Object.entries(tokens.weights))out.push(`  --font-weight-${k}: ${v};`);
for(const [k,v] of Object.entries(tokens.spacing))out.push(`  --space-${k}: ${rem(v)};`);
for(const [k,v] of Object.entries(tokens.radii))out.push(`  --radius-${k}: ${v}px;`);
for(const [k,v] of Object.entries(tokens.typography)){
 out.push(`  --type-${k}-size: ${rem(v.mobile[0])};`);
 out.push(`  --type-${k}-line-height: ${rem(v.mobile[1])};`);
 out.push(`  --type-${k}-weight: ${v.weight};`);
}
for(const [k,v] of Object.entries(tokens.foundation))out.push(`  --ds-${k}: ${v};`);
out.push('}', '',`@media (min-width: ${tokens.reference.typeBreakpoint}px) {`, '  :root {');
for(const [k,v] of Object.entries(tokens.typography)){
 out.push(`    --type-${k}-size: ${rem(v.desktop[0])};`);
 out.push(`    --type-${k}-line-height: ${rem(v.desktop[1])};`);
}
out.push('  }','}','');
for(const [key,b] of Object.entries(tokens.brands)){
  const sel = key === 'bedding' ? '[data-brand="bedding"], [data-brand="hypercool"]' : `[data-brand="${key}"]`;
  out.push(`${sel} {`,
  `  --primary: ${b.primary};`,
  `  --primary-foreground: ${b.onPrimary};`,
  `  --accent: ${b.accent};`,
  `  --accent-foreground: ${b.onAccent};`,
  `  --brand-surface: ${b.surface};`,
  `  --brand-ink: ${b.ink};`,
  `  --foreground: ${b.ink};`,
  `  --card-foreground: ${b.ink};`,
  `  --secondary: ${b.surface};`,
  `  --secondary-foreground: ${b.ink};`,
  `  --popover: #FFFFFF;`,
  `  --popover-foreground: ${b.ink};`,
  `  --destructive: ${tokens.foundation.error};`,
  `  --interactive-text: ${key==='sunset'?b.ink:b.primary};`,
  `  --ring: ${key==='sunset'?'#1C1526':b.primary};`,
  `  --radius: ${tokens.radii.control}px;`,
  `  --status-success-ink: ${tokens.foundation.success};`,
  `  --status-success-surface: #EEF8F3;`,
  '}', '');
}
out.push(
  ':root {',
  '  --background: var(--ds-canvas);',
  '  --foreground: var(--ds-ink, #1A1829);',
  '  --card: var(--ds-card);',
  '  --card-foreground: #1A1829;',
  '  --border: var(--ds-border);',
  '  --input: var(--ds-border);',
  '  --muted: #F1F3F7;',
  '  --muted-foreground: #647086;',
  '}',
  '',
  '.dark, html.dark {',
  '  --ds-canvas: #090B0F;',
  '  --ds-card: #121620;',
  '  --ds-border: #232A3B;',
  '  --background: #090B0F;',
  '  --foreground: #F1F5F9;',
  '  --card: #121620;',
  '  --card-foreground: #F1F5F9;',
  '  --border: #232A3B;',
  '  --input: #232A3B;',
  '  --muted: #1A2130;',
  '  --muted-foreground: #94A3B8;',
  '  --popover: #121620;',
  '  --popover-foreground: #F1F5F9;',
  '  --interactive-text: #5D8EF7;',
  '  --brand-surface: #121A2C;',
  '  --brand-ink: #F1F5F9;',
  '  --secondary: #1A233A;',
  '  --secondary-foreground: #F1F5F9;',
  '  --ring: #5D8EF7;',
  '  --status-success-ink: #4ADE80;',
  '  --status-success-surface: #0E2A1D;',
  '}',
  '',
  ':root:not([data-brand]) {',
  '  --primary: #1C46B4;',
  '  --primary-foreground: #FFFFFF;',
  '  --accent: #2E62ED;',
  '  --accent-foreground: #FFFFFF;',
  '  --brand-surface: #F5F7FD;',
  '  --brand-ink: #1A1829;',
  '  --ring: #1C46B4;',
  '  --interactive-text: #1C46B4;',
  '  --secondary: #F5F7FD;',
  '  --secondary-foreground: #1A1829;',
  '  --popover: #FFFFFF;',
  '  --popover-foreground: #1A1829;',
  '  --destructive: #B42318;',
  '  --radius: 8px;',
  '  --status-success-ink: #167347;',
  '  --status-success-surface: #EEF8F3;',
  '}',
  ''
);

for(const [key, b] of Object.entries(tokens.brands)){
  const sel = key === 'bedding' ? '.dark [data-brand="bedding"], .dark [data-brand="hypercool"], html.dark[data-brand="bedding"], html.dark[data-brand="hypercool"]' : `.dark [data-brand="${key}"], html.dark[data-brand="${key}"]`;
  const darkSurface = key === 'helix' ? '#1D172A' : key === 'sunset' ? '#261710' : '#121A2C';
  const darkSecondary = key === 'helix' ? '#261F38' : key === 'sunset' ? '#382218' : '#1A233A';
  const darkText = key === 'sunset' ? '#FFA566' : key === 'helix' ? '#A78BFA' : '#5D8EF7';
  out.push(
    `${sel} {`,
    `  --brand-surface: ${darkSurface};`,
    `  --brand-ink: #F1F5F9;`,
    `  --foreground: #F1F5F9;`,
    `  --card-foreground: #F1F5F9;`,
    `  --secondary: ${darkSecondary};`,
    `  --secondary-foreground: #F1F5F9;`,
    `  --popover: #121620;`,
    `  --popover-foreground: #F1F5F9;`,
    `  --interactive-text: ${darkText};`,
    `}`,
    ''
  );
}
writeFileSync(path.join(root,'src/styles/generated-tokens.css'),out.join('\n')+'\n');
console.log('Generated CSS for '+Object.keys(tokens.brands).length+' brands and '+Object.keys(tokens.typography).length+' responsive typography roles');
